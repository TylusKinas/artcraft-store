//! DepthCraft: depth-map processing plugin for EffectCraft.
//!
//! Complies with EffectCraft Effect Plug-in API v1 (see `docs/plugins.md`).
//!
//! Depth maps come from `depthcraft-cli` (Depth Anything V3 via ONNX Runtime, CPU or GPU). A wasm
//! plug-in cannot run a neural network inside EffectCraft: the host interprets wasm (wasmi) with a
//! fuel budget of 50M + 20k instructions per pixel, which even MiDaS Small exhausts (the frame then
//! silently stays unchanged). So this plug-in post-processes the depth-map layer the CLI writes:
//! remap, gamma, invert, smoothing, grayscale, heatmap, fog layer, slice, cutout.

pub mod estimator;
pub mod filter;
pub mod models;
#[cfg(feature = "onnx")]
pub mod onnx;
pub mod pipeline;
pub mod temporal;

